"""Generate docs/models.md from the model registry (single source of truth for controls)."""
from pathlib import Path

import soundlab
from soundlab.core import REGISTRY, STAGES

out = ["# Model reference", "", "Generated by `python tools/gen_model_docs.py` from the code. Every control lists its unit,",
       "realistic range and meaning. `automatable` controls accept a breakpoint list `[[t, v], ...]`.", ""]
for st in STAGES:
    ms = [m for m in REGISTRY.values() if m.stage == st]
    if not ms:
        continue
    out += [f"## Stage: {st}", ""]
    for m in ms:
        out += [f"### `{m.name}`", "", m.doc, ""]
        out += ["| control | default | unit | range / choices | meaning |", "|---|---|---|---|---|"]
        for p in m.params:
            rng = f"{p.lo} .. {p.hi}" if (p.lo is not None or p.hi is not None) else (", ".join(p.choices) if p.choices else "")
            auto = " (automatable)" if p.automatable else ""
            src = f" Source: {p.source}." if p.source else ""
            out.append(f"| `{p.name}` | `{p.default}` | {p.unit} | {rng} | {p.doc}{auto}{src} |")
        if m.sources:
            out += ["", "Sources: " + "; ".join(m.sources)]
        out.append("")
Path(__file__).resolve().parents[1].joinpath("docs/models.md").write_text("\n".join(out))
print("wrote docs/models.md")
